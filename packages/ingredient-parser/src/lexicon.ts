/** Words that, trailing the noun phrase, are preparation notes ("butter softened"). */
export const TRAILING_PREP: ReadonlySet<string> = new Set(
  [...PREP_WORDS].filter((w) => w !== "ground" && w !== "mixed"),
);

/** Phrases at the end of the noun phrase that are qualifiers, not part of the name. */
const keepText = (matched: string): string =>
  matched
    .replace(/^[,\s]+/, "")
    .trim()
    .toLowerCase();

export const QUALIFIER_SUFFIXES: readonly {
  re: RegExp;
  /** Text for `prepNote`: fixed, taken from the matched text, or none. */
  note: string | ((matched: string) => string) | null;
  optional?: boolean;
}[] = [
  { re: /(?:,?\s*(?:and|or)\s+)?(?:more\s+)?to taste$/i, note: "to taste" },
  { re: /(?:,?\s*)(?:or\s+)?as needed$/i, note: "as needed" },
  { re: /(?:,?\s*)(?:if|as)\s+(?:needed|desired|necessary)$/i, note: null },
  { re: /(?:,?\s*)\(?optional\)?$/i, note: null, optional: true },
  { re: /(?:,?\s*)divided$/i, note: "divided" },
  { re: /(?:,?\s*)plus (?:more|extra|additional)\b.*$/i, note: keepText },
  { re: /(?:,?\s*)(?:at )?room temp(?:erature)?$/i, note: keepText },
  { re: /(?:,?\s*)cut (?:in|into) [^,]+$/i, note: keepText },
  {
    re: /(?:,?\s*)for (?:the )?(?:serving|garnish|garnishing|frying|dusting|greasing|drizzling|brushing|topping|sprinkling|decorating|pan|baking sheet|grill|table|dipping|rolling|coating|basting|searing|cooking|sauteing|sautéing|deep[- ]frying|dredging|the pan|the dough|the top|the tops|finishing|rimming|cooking the [a-z ]+)(?: [a-z]+)?$/i,
    note: keepText,
  },
];

