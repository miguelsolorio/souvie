// Turns tokens into CSS custom properties. Shared by tailwind.preset.js (NativeWind and web
// Tailwind) and apps/marketing/scripts/sync-brand.mjs, so the two never drift.
// Plain, erasable TypeScript only: Node loads this file directly.

import type { ColorMode } from "./tokens.ts";
import { tokens } from "./tokens.ts";

export type ColorFormat = "hex" | "triplet";
export type CssVars = Record<string, string>;

/** `surfaceRaised` -> `surface-raised`. */
export function kebab(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

/** `#2F6B4F` -> `47 107 79`, the form Tailwind needs for `rgb(var(--x) / <alpha-value>)`. */
export function hexToTriplet(hex: string): string {
  const match = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(hex);
  if (!match) throw new Error(`Not a 6-digit hex color: ${hex}`);
  return match
    .slice(1, 4)
    .map((part) => Number.parseInt(part, 16))
    .join(" ");
}

function color(hex: string, format: ColorFormat): string {
  return format === "triplet" ? hexToTriplet(hex) : hex;
}

/** Semantic colors for one mode: `--color-surface`, `--color-text-muted`, and so on. */
export function colorVars(mode: ColorMode, format: ColorFormat = "hex"): CssVars {
  const vars: CssVars = {};
  for (const [name, hex] of Object.entries(tokens.color[mode])) {
    vars[`--color-${kebab(name)}`] = color(hex, format);
  }
  return vars;
}

/** Fixed scales: `--color-primary-600`. The same in both modes. */
export function scaleVars(format: ColorFormat = "hex"): CssVars {
  const vars: CssVars = {};
  for (const [family, steps] of Object.entries(tokens.color.scale)) {
    for (const [step, hex] of Object.entries(steps)) {
      vars[`--color-${family}-${step}`] = color(hex, format);
    }
  }
  return vars;
}

const px = (value: number): string => `${value}px`;
const rem = (value: number): string => `${value / 16}rem`;

export function shadowCss(shadow: (typeof tokens.shadow)[keyof typeof tokens.shadow]): string {
  const rgb = hexToTriplet(shadow.color);
  return `${px(shadow.offsetX)} ${px(shadow.offsetY)} ${px(shadow.blur)} ${px(shadow.spread)} rgb(${rgb} / ${shadow.opacity})`;
}

/** Type, space, radius, and shadow. Mode independent. Sizes are rem on the web. */
export function layoutVars(): CssVars {
  const vars: CssVars = {
    "--font-sans": tokens.type.fontFamily.sans,
    "--font-display": tokens.type.fontFamily.display,
  };
  for (const [name, spec] of Object.entries(tokens.type)) {
    if (name === "fontFamily") continue;
    const { size, lineHeight, weight, letterSpacing } = spec as {
      size: number;
      lineHeight: number;
      weight: string;
      letterSpacing: number;
    };
    vars[`--text-${name}-size`] = rem(size);
    vars[`--text-${name}-line`] = rem(lineHeight);
    vars[`--text-${name}-weight`] = weight;
    vars[`--text-${name}-tracking`] = `${letterSpacing / size}em`;
  }
  for (const [step, value] of Object.entries(tokens.space)) vars[`--space-${step}`] = rem(value);
  for (const [name, value] of Object.entries(tokens.radius)) {
    vars[`--radius-${name}`] = name === "full" ? "9999px" : rem(value);
  }
  for (const [name, value] of Object.entries(tokens.shadow))
    vars[`--shadow-${name}`] = shadowCss(value);
  return vars;
}

function block(selector: string, vars: CssVars, indent = ""): string {
  const lines = Object.entries(vars).map(([key, value]) => `${indent}  ${key}: ${value};`);
  return `${indent}${selector} {\n${lines.join("\n")}\n${indent}}`;
}

/**
 * The full stylesheet for the marketing site. Light is the default. Dark follows the system
 * unless the page pins a theme with `data-theme="light"` or `data-theme="dark"` on <html>.
 */
export function tokensCss(): string {
  const light = colorVars("light");
  const dark = colorVars("dark");
  return [
    "/* Generated by apps/marketing/scripts/sync-brand.mjs from packages/ui/src/tokens.ts. Do not edit. */",
    "",
    block(":root", { "color-scheme": "light dark", ...scaleVars(), ...light, ...layoutVars() }),
    "",
    "@media (prefers-color-scheme: dark) {",
    block(':root:not([data-theme="light"])', dark, "  "),
    "}",
    "",
    block(':root[data-theme="light"]', { "color-scheme": "light" }),
    "",
    block(':root[data-theme="dark"]', { "color-scheme": "dark", ...dark }),
    "",
  ].join("\n");
}
