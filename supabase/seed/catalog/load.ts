// Review sheet
// ---------------------------------------------------------------------------------------

const cell = (s: string): string => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const title = (s: string): string => s.replace(/_/g, " ");

export interface CatalogStats {
  recipes: number;
  cuisines: Map<string, number>;
  proteins: Map<string, number>;
  diets: Map<string, number>;
  allergenFree: number;
  lines: number;
  resolvedLines: number;
  quick: number;
  kidFriendly: number;
  pantry: number;
  methods: Map<string, number>;
}

function bump(map: Map<string, number>, key: string): void {
  map.set(key, (map.get(key) ?? 0) + 1);
}

export function catalogStats(recipes: readonly CatalogRecipe[], seed: Seed): CatalogStats {
  const categories = new Map(seed.ingredients.map((i) => [i.name, i.category]));
  const stats: CatalogStats = {
    recipes: recipes.length,
    cuisines: new Map(),
    proteins: new Map(),
    diets: new Map(),
    allergenFree: 0,
    lines: 0,
    resolvedLines: 0,
    quick: 0,
    kidFriendly: 0,
    pantry: 0,
    methods: new Map(),
  };
  for (const r of recipes) {
    bump(stats.cuisines, r.cuisine);
    const protein = proteinOf(r.tags);
    if (protein) bump(stats.proteins, protein);
    for (const tag of r.tags) {
      if ((DIET_TAGS as readonly string[]).includes(tag)) bump(stats.diets, tag);
    }
    if (analyzeRecipe(r.ingredients, (n) => categories.get(n)).allergenFree) stats.allergenFree++;
    stats.lines += r.ingredients.length;
    stats.resolvedLines += r.ingredients.filter((l) => l.ingredientId !== null).length;
    if (r.prepMin + r.cookMin <= COVERAGE.quickMinutes) stats.quick++;
    if (r.tags.includes("kid_friendly")) stats.kidFriendly++;
    if (r.tags.includes("pantry")) stats.pantry++;
    for (const tag of r.tags) {
      if (
        [
          "sheet_pan",
          "one_pot",
          "skillet",
          "slow_cooker",
          "pressure_cooker",
          "grill",
          "no_cook",
          "bake",
        ].includes(tag)
      ) {
        bump(stats.methods, tag);
      }
    }
  }
  return stats;
}

const counts = (map: Map<string, number>, order?: readonly string[]): string => {
  const keys = order ? order.filter((k) => map.has(k)) : [...map.keys()].sort();
  return keys.map((k) => `${title(k)} ${map.get(k)}`).join(", ");
};

export function renderReviewSheet(
  recipes: readonly CatalogRecipe[],
  seed: Seed,
  runs: readonly DraftRun[] | null,
): string {
  const categories = new Map(seed.ingredients.map((i) => [i.name, i.category]));
  const stats = catalogStats(recipes, seed);
  const share = stats.lines === 0 ? 0 : (stats.resolvedLines / stats.lines) * 100;
  const spent = runs ? runs.reduce((sum, run) => sum + run.costUsd, 0) : null;
  const rejected = runs ? runs.reduce((sum, run) => sum + run.rejected.length, 0) : null;
  // A slot abandoned after two attempts may be drafted again by a later run.
  const written = new Set(runs?.flatMap((run) => run.written) ?? []);
  const abandoned = [...new Set(runs?.flatMap((run) => run.abandoned) ?? [])];
  const redone = abandoned.filter((slug) => written.has(slug)).length;
  const rejectedNote =
    abandoned.length === 0
      ? ""
      : `; ${abandoned.length} recipe(s) were abandoned after two attempts and ${redone} of them drafted again in a later run`;
  const keptCost = recipes.reduce((sum, r) => sum + r.draft.costUsd, 0);

  const out: string[] = [
    "# Starter catalog review sheet",
    "",
    "Generated by `node supabase/seed/catalog/load.ts` from `recipes/*.json`. Do not edit by hand.",
    "",
    "The catalog is the set of original dinner recipes every new household can plan from on day one.",
    "Each recipe was drafted by `claude-sonnet-5-5` from a spec (cuisine, protein, method, time), with",
    "no named source. Nothing here has been loaded into the hosted project yet.",
    "",
    "## How to review",
    "",
    "1. Read the recipe table. The **Allergens** column is conservative: it lists every allergen a line might carry (soy sauce counts as soy and wheat), and a recipe with a line nobody could identify is marked unclear.",
    "2. Open any recipe's JSON (the title links to it) and read the lines and steps.",
    "3. To change a recipe, edit its JSON, then run `node supabase/seed/catalog/load.ts` (this sheet and `../20_catalog.sql` are rewritten) and `pnpm test`.",
    "4. To drop a recipe, delete its file and tell the orchestrator. Never rename a slug: ids derive from it, and a new slug is a new recipe.",
    '5. When you approve, the orchestrator loads `20_catalog.sql` into the hosted project (`supabase/seed/README.md`, "Loading the hosted project").',
    "",
    "## Summary",
    "",
    "| | |",
    "|---|---|",
    `| Recipes | ${stats.recipes} |`,
    `| Cuisines | ${stats.cuisines.size}: ${counts(stats.cuisines)} |`,
    `| Protein | ${counts(stats.proteins, PROTEIN_TAGS)} |`,
    `| Diet tags | ${counts(stats.diets, DIET_TAGS)} |`,
    `| Contain none of the nine allergens | ${stats.allergenFree} |`,
    `| Total time 35 minutes or less | ${stats.quick} |`,
    `| Kid friendly / pantry | ${stats.kidFriendly} / ${stats.pantry} |`,
    `| Ingredient lines | ${stats.lines} |`,
    `| Lines matched to the ontology | ${stats.resolvedLines} (${share.toFixed(1)}%) |`,
    `| Drafting spend, all runs (rejected drafts included) | ${spent === null ? "not recorded" : `$${spent.toFixed(2)} across ${runs?.length ?? 0} run(s)`} |`,
    `| Drafts rejected by validation | ${rejected === null ? "not recorded" : `${rejected}${rejectedNote}`} |`,
    `| Cost recorded in the kept files | $${keptCost.toFixed(2)} |`,
    "",
    "## Recipes",
    "",
    "| Recipe | Cuisine | Protein | Minutes | Diet | Allergens |",
    "|---|---|---|---|---|---|",
  ];

  const unresolved: {
    recipe: CatalogRecipe;
    text: string;
    parsed: string | null;
    confidence: number | null;
  }[] = [];
  for (const r of recipes) {
    const facts = analyzeRecipe(r.ingredients, (n) => categories.get(n));
    const diets = r.tags.filter((t) => (DIET_TAGS as readonly string[]).includes(t));
    const present = ALLERGENS.filter((a) => facts.allergens.includes(a)).map(title);
    const allergens =
      present.length === 0
        ? facts.unknownLines.length > 0
          ? "unclear"
          : "none"
        : present.join(", ") + (facts.unknownLines.length > 0 ? " (and unclear)" : "");
    out.push(
      `| [${cell(r.title)}](recipes/${r.slug}.json) | ${cell(r.cuisine)} | ${cell(proteinOf(r.tags) ?? "")} | ${r.prepMin + r.cookMin} | ${diets.length > 0 ? diets.map(title).join(", ") : "none"} | ${allergens} |`,
    );
    for (const l of r.ingredients) {
      if (l.ingredientId === null) {
        unresolved.push({
          recipe: r,
          text: l.rawText,
          parsed: l.ingredientName,
          confidence: l.parseConfidence,
        });
      }
    }
  }

  out.push("", "## Ingredient lines that did not resolve", "");
  if (unresolved.length === 0) {
    out.push("None. Every line matched an ontology ingredient.");
  } else {
    out.push(
      `${unresolved.length} of ${stats.lines} lines. These keep their text and have no ingredient id, so the grocery list shows them as written.`,
      "",
      "| Recipe | Line | Parsed as | Confidence |",
      "|---|---|---|---|",
    );
    for (const u of unresolved) {
      out.push(
        `| ${cell(u.recipe.title)} | ${cell(u.text)} | ${u.parsed === null ? "nothing" : cell(u.parsed)} | ${u.confidence === null ? "" : u.confidence} |`,
      );
    }
  }
  out.push("");
  return out.join("\n");
}

// ---------------------------------------------------------------------------------------
// Command line
// ---------------------------------------------------------------------------------------

function main(): void {
  const recipes = readCatalog();
  const seed = readSeed();
  const sql = renderCatalogSql(recipes);
  const sheet = renderReviewSheet(recipes, seed, readDraftLog());

  if (process.argv.includes("--check")) {
    const stale: string[] = [];
    const read = (path: string): string => {
      try {
        return readFileSync(path, "utf8");
      } catch {
        return "";
      }
    };
    if (read(CATALOG_SQL_PATH) !== sql) stale.push("supabase/seed/20_catalog.sql");
    if (read(REVIEW_SHEET_PATH) !== sheet) stale.push("supabase/seed/catalog/README.md");
    if (stale.length > 0) {
      console.error(`${stale.join(" and ")} out of date. Run: node supabase/seed/catalog/load.ts`);
      process.exit(1);
    }
    console.log("20_catalog.sql and catalog/README.md are up to date");
    return;
  }

  writeFileSync(CATALOG_SQL_PATH, sql);
  writeFileSync(REVIEW_SHEET_PATH, sheet);
  const lines = recipes.reduce((sum, r) => sum + r.ingredients.length, 0);
  console.log(
    `wrote ${CATALOG_SQL_PATH} and ${REVIEW_SHEET_PATH}: ${recipes.length} recipes, ${lines} ingredient lines`,
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
