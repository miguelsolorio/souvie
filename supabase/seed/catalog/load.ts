// SQL
// ---------------------------------------------------------------------------------------

const q = (s: string): string => `'${s.replace(/'/g, "''")}'`;
const qn = (s: string | null): string => (s === null ? "null" : q(s));
const num = (v: number | null): string => (v === null ? "null" : String(v));

function chunks<T>(list: readonly T[], size: number): T[][] {
  const out: T[][] = [];
  for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size));
  return out;
}

export function renderCatalogSql(recipes: readonly CatalogRecipe[]): string {
  const lines: string[] = [
    "-- Generated by supabase/seed/catalog/load.ts from supabase/seed/catalog/recipes/*.json.",
    "-- Do not edit by hand: edit the JSON and run `node supabase/seed/catalog/load.ts`.",
    "--",
    "-- The starter catalog (WS16): original dinner recipes drafted for the app. Rows are public",
    "-- catalog recipes: household_id null, visibility 'catalog', source_type 'ai', no source_url,",
    "-- no created_by, no embedding (WS06 backfill fills it).",
    "--",
    "-- Idempotent: upserts recipes and ingredient lines by their deterministic ids. It never",
    "-- deletes, so a line removed from a JSON file stays in a database that already has it.",
    "-- A reload keeps embeddings unless the recipe's title, description, tags or cuisine changed.",
    "-- Loads after 10_ingredients.sql (name order): ingredient_id references public.ingredients.",
    "",
  ];

  for (const part of chunks(recipes, 20)) {
    lines.push(
      "insert into public.recipes (id, household_id, title, description, image_url, source_type, source_url, servings, prep_min, cook_min, instructions, nutrition, tags, cuisine, visibility, created_by)",
      "values",
      part
        .map((r) => {
          const steps = JSON.stringify(r.instructions.map((text, i) => ({ step: i + 1, text })));
          const tags = `array[${r.tags.map(q).join(", ")}]::text[]`;
          return `  (${q(r.id)}, null, ${q(r.title)}, ${q(r.description)}, null, 'ai', null, ${r.servings}, ${r.prepMin}, ${r.cookMin}, ${q(steps)}::jsonb, null, ${tags}, ${q(r.cuisine)}, 'catalog', null)`;
        })
        .join(",\n"),
      "on conflict (id) do update set",
      "  household_id = null,",
      "  title = excluded.title,",
      "  description = excluded.description,",
      "  image_url = null,",
      "  source_type = 'ai',",
      "  source_url = null,",
      "  servings = excluded.servings,",
      "  prep_min = excluded.prep_min,",
      "  cook_min = excluded.cook_min,",
      "  instructions = excluded.instructions,",
      "  nutrition = null,",
      "  tags = excluded.tags,",
      "  cuisine = excluded.cuisine,",
      "  visibility = 'catalog',",
      "  created_by = null,",
      "  embedding = case",
      "    when (public.recipes.title, public.recipes.description, public.recipes.tags, public.recipes.cuisine)",
      "      is distinct from (excluded.title, excluded.description, excluded.tags, excluded.cuisine)",
      "    then null",
      "    else public.recipes.embedding",
      "  end;",
      "",
    );
  }

  const rows = recipes.flatMap((r) => r.ingredients.map((line) => ({ recipe: r, line })));
  for (const part of chunks(rows, 150)) {
    lines.push(
      "insert into public.recipe_ingredients (id, recipe_id, position, group_name, raw_text, qty, qty_max, unit, ingredient_id, prep_note, optional, parse_confidence)",
      "values",
      part
        .map(
          ({ recipe: r, line: l }) =>
            `  (${q(lineId(r.slug, l.position))}, ${q(r.id)}, ${l.position}, ${qn(l.groupName)}, ${q(l.rawText)}, ${num(l.qty)}, ${num(l.qtyMax)}, ${qn(l.unit)}, ${qn(l.ingredientId)}, ${qn(l.prepNote)}, ${l.optional}, ${num(l.parseConfidence)})`,
        )
        .join(",\n"),
      "on conflict (id) do update set",
      "  recipe_id = excluded.recipe_id,",
      "  position = excluded.position,",
      "  group_name = excluded.group_name,",
      "  raw_text = excluded.raw_text,",
      "  qty = excluded.qty,",
      "  qty_max = excluded.qty_max,",
      "  unit = excluded.unit,",
      "  ingredient_id = excluded.ingredient_id,",
      "  prep_note = excluded.prep_note,",
      "  optional = excluded.optional,",
      "  parse_confidence = excluded.parse_confidence;",
      "",
    );
  }
  return lines.join("\n");
}

