// Starter catalog loader (WS16).
//
// Reads supabase/seed/catalog/recipes/*.json and renders two files:
//   supabase/seed/20_catalog.sql        what `supabase db reset` (and a hosted `psql -f`) runs
//   supabase/seed/catalog/README.md     the review sheet for the person who approves the content
//
//   node supabase/seed/catalog/load.ts            write both
//   node supabase/seed/catalog/load.ts --check    fail if either file is out of date
//
// The SQL loads after 10_ingredients.sql (name order) because recipe_ingredients.ingredient_id
// references ingredients. It is idempotent: it upserts recipes and lines by their deterministic
// ids (spec.ts) and never deletes. No database is needed to render it, because the JSON already
// holds each ingredient's id.
//
// Plain Node, no dependencies, like supabase/seed/load.ts.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { readSeed, type Seed } from "../load.ts";
import {
  ALLERGENS,
  analyzeRecipe,
  type CatalogRecipe,
  COVERAGE,
  DIET_TAGS,
  lineId,
  PROTEIN_TAGS,
  proteinOf,
  shapeProblems,
} from "./spec.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
export const RECIPES_DIR = join(HERE, "recipes");
export const DRAFT_LOG_PATH = join(HERE, "draft-log.json");
export const CATALOG_SQL_PATH = join(HERE, "..", "20_catalog.sql");
export const REVIEW_SHEET_PATH = join(HERE, "README.md");

// ---------------------------------------------------------------------------------------
// Reading
// ---------------------------------------------------------------------------------------

/** Every recipe file, sorted by slug. Throws on a file that is not a valid recipe. */
export function readCatalog(dir: string = RECIPES_DIR): CatalogRecipe[] {
  const files = readdirSync(dir)
    .filter((name) => name.endsWith(".json"))
    .sort();
  const recipes: CatalogRecipe[] = [];
  const problems: string[] = [];
  for (const name of files) {
    const value: unknown = JSON.parse(readFileSync(join(dir, name), "utf8"));
    const found = shapeProblems(value);
    const recipe = value as CatalogRecipe;
    if (found.length === 0 && name !== `${recipe.slug}.json`) {
      found.push(`file name must be ${recipe.slug}.json`);
    }
    for (const p of found) problems.push(`${name}: ${p}`);
    recipes.push(recipe);
  }
  if (problems.length > 0) throw new Error(`invalid catalog files:\n${problems.join("\n")}`);
  return recipes;
}

export interface DraftRun {
  at: string;
  requested: number;
  written: string[];
  rejected: { slug: string; attempt: number; problems: string[] }[];
  abandoned: string[];
  costUsd: number;
}

/** The run log the drafting script keeps. Null when no run was recorded. */
export function readDraftLog(path: string = DRAFT_LOG_PATH): DraftRun[] | null {
  try {
    const parsed = JSON.parse(readFileSync(path, "utf8")) as { runs?: DraftRun[] };
    return Array.isArray(parsed.runs) ? parsed.runs : null;
  } catch {
    return null;
  }
}

